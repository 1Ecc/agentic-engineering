export function buildNodeFromCurlPrompt(input: {
  curl?: string;
  description?: string;
  name?: string;
  currentNode?: unknown;
}): string {
  return [
    "你是企业自动化平台的 HTTP 节点建模助手。请把用户提供的 curl 命令或现有节点修改要求转换成一个可执行的 NodeDefinition JSON。",
    "",
    "只输出 JSON 对象，不要 Markdown，不要解释。",
    "",
    "NodeDefinition 结构要求：",
    "{",
    '  "type": "recorded.platform_action",',
    '  "category": "recorded",',
    '  "platform": "serviceforce | jiuqiu | spos | other",',
    '  "platform_label": "平台显示名",',
    '  "name": "节点名称",',
    '  "description": "节点说明",',
    '  "inputs": [{ "name": "字段名", "type": "string|text|number|boolean|object|array", "label": "显示名", "required": true }],',
    '  "outputs": [{ "name": "字段名", "type": "string|text|number|boolean|object|array", "label": "显示名" }],',
    '  "handler": {',
    '    "kind": "recorded_http",',
    '    "spec": {',
    '      "method": "GET|POST|PUT|PATCH|DELETE",',
    '      "url_template": "完整 URL，可使用 {{ inputs.xxx }}",',
    '      "headers": { "header": "value" },',
    '      "query_template": { "q": "{{ inputs.q }}" },',
    '      "body_template": "{\\"x\\":\\"{{ inputs.x }}\\"}",',
    '      "response_mapping": { "data": "$" }',
    "    }",
    "  },",
    '  "metadata": { "source_type": "manual", "visibility": "private", "last_trial_status": "untested" }',
    "}",
    "",
    "规则：",
    "1. category 必须是 recorded，handler.kind 必须是 recorded_http。",
    "2. type 使用小写英文、数字、点、下划线，建议 recorded.<domain>_<action>。",
    "3. 不确定响应结构时，outputs 使用 data: object，response_mapping 使用 { data: \"$\" }。",
    "4. 如果提供 curl，curl 中的动态业务参数应抽成 inputs，并在 url_template/query_template/body_template 中使用 {{ inputs.name }}。",
    "5. Cookie、Authorization、X-CSRF、token、secret、password、credential 等鉴权或凭证字段必须从 headers、query_template、body_template、response_mapping 中移除，不允许输出到节点 JSON；运行时会自动复用浏览器登录态。",
    "6. 如果用户给了名称或描述，优先采用。",
    "7. 如果提供了现有节点，请在现有节点基础上修改；除非用户明确要求，尽量保留 type，避免影响已引用的工作流。",
    "",
    `用户名称：${input.name?.trim() || "(未提供)"}`,
    `用户描述：${input.description?.trim() || "(未提供)"}`,
    input.currentNode ? `现有节点：\n${JSON.stringify(input.currentNode, null, 2)}` : "",
    "curl：",
    input.curl || "(未提供，请基于现有节点和用户描述修改)",
  ].join("\n");
}
